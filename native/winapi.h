#define BIND(lib,name) name=(void*)GetProcAddress(lib,#name)
static void InitAPI(void) {
  H k=LoadLibraryW(L"kernel32.dll"),u=LoadLibraryW(L"user32.dll"),s=LoadLibraryW(L"shell32.dll"),o=LoadLibraryW(L"ole32.dll");
  BIND(k,GetModuleHandleW);BIND(k,GetModuleFileNameW);BIND(k,GetSystemDirectoryW);BIND(k,GetTempPathW);BIND(k,GetCurrentProcessId);BIND(k,GetTickCount64);
  BIND(k,GetCommandLineW);BIND(k,LocalFree);BIND(k,CopyFileW);BIND(s,CommandLineToArgvW);
  BIND(k,CreateDirectoryW);BIND(k,GetFileAttributesW);BIND(k,CreateFileW);BIND(k,ReadFile);BIND(k,WriteFile);BIND(k,GetFileSizeEx);BIND(k,CloseHandle);BIND(k,CreateProcessW);
  BIND(k,WaitForSingleObject);BIND(k,GetExitCodeProcess);BIND(k,SetEnvironmentVariableW);BIND(k,CreateMutexW);BIND(k,GetLastError);
  BIND(k,FindResourceW);BIND(k,LoadResource);BIND(k,LockResource);BIND(k,SizeofResource);BIND(k,MultiByteToWideChar);BIND(k,GetFileSize);BIND(k,DeleteFileW);BIND(k,RemoveDirectoryW);
  BIND(u,RegisterClassW);BIND(u,CreateWindowExW);BIND(u,DefWindowProcW);BIND(u,DestroyWindow);BIND(u,ShowWindow);BIND(u,UpdateWindow);BIND(u,PeekMessageW);BIND(u,TranslateMessage);BIND(u,DispatchMessageW);BIND(u,SetWindowTextW);BIND(u,MessageBoxW);BIND(u,LoadIconW);BIND(u,LoadCursorW);
  BIND(s,SHBrowseForFolderW);BIND(s,SHGetPathFromIDListW);BIND(o,CoInitializeEx);BIND(o,CoTaskMemFree);
}
